/*
  state.js
  ==============================================================
  このファイルの役割：
  アプリ全体で共有する「今の状態」を持つ変数を、すべてここにまとめている。

  例えば「今カレンダーに表示している年月」「登録済みの予定」
  「今複数選択モード中かどうか」などは、
  カレンダー本体・サイドバー・モーダルなど複数の場所から
  参照したり書き換えたりする必要がある。
  そのため、こうした変数は1つのファイルにまとめておき、
  他のファイルからは同じ変数名でそのままアクセスする、という作り方にしている。

  【注意・影響範囲】
  ここの変数は「グローバル変数」なので、どのJSファイルからも
  そのまま読み書きできる。裏を返すと、変数名を変更すると
  他の全ファイルに影響するので、名前を変える場合は
  必ず全ファイルを横断して検索すること。

  読み込み順について：
  index.html では、このファイルを他のどのJSファイルよりも
  先に読み込む必要がある（他のファイルがここの変数を使うため）。
*/

